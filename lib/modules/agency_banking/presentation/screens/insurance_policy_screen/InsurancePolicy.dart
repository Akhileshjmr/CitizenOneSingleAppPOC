class InsurancePolicy {
  final String name;
  final String type;
  final String coverage;
  final String policyTerm;
  final String premium;
  final String repayment;
  final String price;

  InsurancePolicy({
    required this.name,
    required this.type,
    required this.coverage,
    required this.policyTerm,
    required this.price,
    required this.premium,
    required this.repayment,
  });
}
